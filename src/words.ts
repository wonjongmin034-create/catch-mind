export type Level = 'easy' | 'hard' | 'mix'

export interface Word {
  w: string
  c: string
  h?: boolean // 어려운 단어 (점수 1.5배)
}

export const ALL_WORDS: Word[] = Object.entries(WORDS).flatMap(([c, ws]) => ws.map((w) => ({ w, c })))
export const ALL_HARD: Word[] = Object.entries(HARD_WORDS).flatMap(([c, ws]) =>
  ws.map((w) => ({ w, c, h: true })),
)

/**
 * 안 나온 단어 중에서 무작위로 n개. 다 써 버렸으면 가장 오래전에 나온 것부터 다시.
 * recent: 최근에 나온 단어 (오래된 것 → 최근 순)
 */
function pickFrom(all: Word[], n: number, recent: string[], taken: Set<string>): Word[] {
  const seenAt = new Map(recent.map((w, i) => [w, i]))
  const fresh = all.filter((x) => !seenAt.has(x.w) && !taken.has(x.w))
  const out: Word[] = []
  while (out.length < n && fresh.length) {
    const [x] = fresh.splice(Math.floor(Math.random() * fresh.length), 1)
    out.push(x)
  }
  if (out.length < n) {
    const old = all
      .filter((x) => seenAt.has(x.w) && !taken.has(x.w))
      .sort((a, b) => seenAt.get(a.w)! - seenAt.get(b.w)!)
    out.push(...old.slice(0, n - out.length))
  }
  for (const x of out) taken.add(x.w)
  return out
}

/** 최근에 나온 단어를 피해서 n개 뽑기. 섞어서 = 쉬운 것 1개 + 어려운 것 나머지 */
export function pickWords(n: number, recent: string[], level: Level = 'hard'): Word[] {
  const taken = new Set<string>()
  if (level === 'easy') return pickFrom(ALL_WORDS, n, recent, taken)
  if (level === 'hard') return pickFrom(ALL_HARD, n, recent, taken)
  const mixed = [...pickFrom(ALL_WORDS, 1, recent, taken), ...pickFrom(ALL_HARD, n - 1, recent, taken)]
  return mixed.sort(() => Math.random() - 0.5)
}

/** 정답 비교용: 공백·문장부호 제거 + 소문자 ("우유?" → "우유") */
export const norm = (s: string) => s.replace(/[\s.,!?~^'"…·ㅋㅎ]+/g, '').toLowerCase()

/** 한 글자만 다르거나 한 글자 빠진/더한 경우 → "아깝다!" */
export function isClose(guess: string, word: string): boolean {
  const a = [...norm(guess)]
  const b = [...norm(word)]
  if (a.join('') === b.join('') || b.length < 2) return false
  if (a.length === b.length) return a.filter((ch, i) => ch !== b[i]).length === 1
  if (Math.abs(a.length - b.length) !== 1) return false
  const [s, l] = a.length < b.length ? [a, b] : [b, a]
  let i = 0
  let j = 0
  let skipped = false
  while (i < s.length && j < l.length) {
    if (s[i] === l[j]) {
      i++
      j++
    } else if (skipped) return false
    else {
      skipped = true
      j++
    }
  }
  return true
}
